"""Give measured pure codec leaves native local registers, preserving the lift.

The whitelist excludes calls, tail branches and MMIO. All observable register
state is published at every return; instructions and guest memory operations
are unchanged. The color converter has a differential regression oracle.
"""
from pathlib import Path
import json
import re
import shutil
project=Path(__file__).resolve().parents[1]
gen=project/"src/recomp/gen"
targets={0x0039EF90,0x0039CA50,0x0039D1D0,0x0039F1E0}
found=[];sources=[];reference=None
for path in sorted(gen.glob("recomp_[0-9][0-9][0-9][0-9].c")):
    original=project/"bringup/originals"/path.name
    text=(original if original.exists() else path).read_text()
    for address in sorted(targets):
        name=f"sub_{address:08X}"
        match=re.search(r"void "+name+r"\(void\)\n\{",text)
        if not match:continue
        body=text[match.start():text.index("\n}\n",match.end())+3]
        if re.search(r"RECOMP_(?:ABI_CALL|ICALL|ITAIL|CALL)|\bsub_[0-9A-F]{8}\(",body[body.index("{"):]):
            print(f"Retained non-leaf {name}");continue
        if not original.exists():shutil.copy2(path,original)
        if address==0x0039EF90:reference=body.replace(name,name+"_reference",1)
        registers=[r for r in ("eax","ecx","edx","esp","ebx","esi","edi") if re.search(r"\b"+r+r"\b",body)]
        mmx=[r for r in (f"g_mm{i}" for i in range(8)) if re.search(r"\b"+r+r"\b",body)]
        for register in registers:body=re.sub(r"\b"+register+r"\b","local_"+register,body)
        for register in mmx:body=re.sub(r"\b"+register+r"\b","local_"+register,body)
        declarations=[f"    uint32_t local_{r}=g_{r};" for r in registers]
        declarations += [f"    RecompMmx local_{r}={r};" for r in mmx]
        publish=" ".join([f"g_{r}=local_{r};" for r in registers]+[f"{r}=local_{r};" for r in mmx])
        body=body.replace("return;","{ "+publish+" return; }")
        body=body.replace("{\n","{\n"+"\n".join(declarations)+"\n",1)
        sources.append(body);found.append({"address":f"0x{address:08X}","file":path.name})
header='#define RECOMP_GENERATED_CODE\n#include "recomp_types.h"\n#include "recomp_funcs.h"\n'
(gen/"recomp_fastpaths.c").write_text("/* Generated by bringup/optimize_leafs.py. */\n"+header+"\n\n".join(sources))
(project/"bringup/fastpaths.json").write_text(json.dumps(found,indent=2)+"\n")
if reference:(project/"bringup/regression/bink_reference.c").write_text(header+reference)
print(f"Optimized {len(found)} measured codec leaves with complete register publication.")
